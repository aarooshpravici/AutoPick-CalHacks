"""Generate the firmware pin map from robot.yaml; --check detects stale headers."""
import argparse
import math
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[2]


def config_id(base):
    """Fingerprint only the fields compiled into the R4, normalized by type."""
    import hashlib
    import json
    fields = {key: base[key] for key in ('controller', 'left_coil_pins', 'right_coil_pins',
              'invert_left', 'invert_right', 'wiring_confirmed', 'estop_sense_pin')}
    fields.update({key: float(base[key]) for key in ('wheel_diameter_mm', 'half_steps_per_rev',
                  'max_speed_mm_s', 'acceleration_mm_s2', 'stop_acceleration_mm_s2')})
    return hashlib.sha256(json.dumps(fields, sort_keys=True).encode()).hexdigest()[:16]


def render(base):
    if base['controller'] != 'uno_r4_wifi':
        raise ValueError('this firmware requires uno_r4_wifi')
    for side in ('left_coil_pins', 'right_coil_pins'):
        side_pins = base[side]
        if not isinstance(side_pins, list) or len(side_pins) != 4 or len(set(side_pins)) != 4:
            raise ValueError(f'{side} needs exactly four distinct pins')
    pins = base['left_coil_pins'] + base['right_coil_pins']
    if len(pins) != 8 or len(set(pins)) != 8 or any(type(p) is not int or not 2 <= p <= 13 for p in pins):
        raise ValueError('eight distinct digital coil pins in 2..13 required')
    for name in ('wheel_diameter_mm', 'half_steps_per_rev', 'max_speed_mm_s',
                 'acceleration_mm_s2', 'stop_acceleration_mm_s2'):
        if not math.isfinite(base[name]) or base[name] <= 0:
            raise ValueError(f'{name} must be positive and finite')
    if base['max_speed_mm_s'] > 50:
        raise ValueError('28BYJ-48 build cap is 50 mm/s; revalidate hardware before increasing')
    if base['acceleration_mm_s2'] > 1000 or base['stop_acceleration_mm_s2'] > 1000:
        raise ValueError('accelerations are capped at 1000 mm/s^2')
    if base['stop_acceleration_mm_s2'] < base['acceleration_mm_s2']:
        raise ValueError('stop acceleration must be at least the normal acceleration')
    # The loop issues at most one half step per wheel per pass; 28BYJ-48 also stalls
    # well below this rate under load.
    rate = base['max_speed_mm_s'] * base['half_steps_per_rev'] / (math.pi * base['wheel_diameter_mm'])
    if rate > 1000:
        raise ValueError(f'max speed needs {rate:.0f} half steps/s; limit is 1000')
    for key in ('wiring_confirmed', 'invert_left', 'invert_right'):
        if type(base[key]) is not bool:
            raise ValueError(f'{key} must be boolean')
    sense = base['estop_sense_pin']
    if type(sense) is not int or (sense != -1 and (sense in pins or not 2 <= sense <= 13)):
        raise ValueError('E-stop sense must be -1 or a free digital pin')
    def flag(name): return str(base[name]).lower()
    return f'''#pragma once
// Generated by generate_config.py from config/robot.yaml. Do not edit by hand.
namespace wiring {{
constexpr const char* config_id = "{config_id(base)}";
constexpr bool confirmed = {flag('wiring_confirmed')};
constexpr int left_coils[4] = {{{', '.join(map(str, base['left_coil_pins']))}}};
constexpr int right_coils[4] = {{{', '.join(map(str, base['right_coil_pins']))}}};
constexpr int estop_sense = {sense}; // -1: not instrumented; STAT estop cannot detect the switch.
constexpr bool estop_active_low = true;
constexpr bool invert_left = {flag('invert_left')}, invert_right = {flag('invert_right')};
constexpr float wheel_diameter_mm = {float(base['wheel_diameter_mm'])}f;
constexpr float half_steps_per_rev = {float(base['half_steps_per_rev'])}f;
constexpr float max_speed_mm_s = {float(base['max_speed_mm_s'])}f;
constexpr float acceleration_mm_s2 = {float(base['acceleration_mm_s2'])}f;
constexpr float stop_acceleration_mm_s2 = {float(base['stop_acceleration_mm_s2'])}f;
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path, default=ROOT/'config/robot.yaml')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = render(yaml.safe_load(args.config.read_text())['base'])
    path = Path(__file__).parent/'include/pinmap.h'
    if args.check:
        if path.read_text() != result:
            raise SystemExit('Stale firmware pinmap: run generate_config.py')
    else:
        path.write_text(result)


if __name__ == '__main__': main()
